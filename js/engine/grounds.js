export const groundsFor = (type) => GROUNDS.filter((g) => g.types.includes(type));

/** הציון של עילה לפי התשובה. null = לא רלוונטית. */
export function scoreOf(ground, answer) {
  if (!answer) return null;
  if (ground.kind === 'choice') {
    const opt = (ground.options || []).find((o) => o.value === answer.value);
    return opt && opt.score ? opt.score : null;
  }
  if (answer.value === 'yes') return ground.score;
  return null;
}
