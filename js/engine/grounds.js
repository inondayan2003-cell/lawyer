const val = (inputs, id, fallback) => {
  const v = inputs && inputs[id] != null ? String(inputs[id]).trim() : '';
  return v || fallback;
};
const dateVal = (inputs, id, fallback) => {
  const d = parseISO(inputs && inputs[id]);
  return d ? fmt(d) : fallback;
};

